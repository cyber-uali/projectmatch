/* ---------------------------------------------------------------- Логика */
(function () {
  'use strict';

  var DICT = window.PM_I18N;
  var SUPPORTED = ['ru', 'kk'];
  var STORAGE_KEY = 'pm-lang';
  var current = 'ru';

  function readStorage() {
    try { return window.localStorage.getItem(STORAGE_KEY); } catch (e) { return null; }
  }

  function writeStorage(lang) {
    try { window.localStorage.setItem(STORAGE_KEY, lang); } catch (e) { /* приватный режим */ }
  }

  function fromQuery() {
    try {
      return new URLSearchParams(window.location.search).get('lang');
    } catch (e) {
      return null;
    }
  }

  function detect() {
    var fromUrl = fromQuery();
    if (SUPPORTED.indexOf(fromUrl) !== -1) return fromUrl;
    var saved = readStorage();
    if (SUPPORTED.indexOf(saved) !== -1) return saved;
    return 'ru';
  }

  function t(key) {
    var pack = DICT[current] || DICT.ru;
    var value = pack[key];
    if (value === undefined) value = DICT.ru[key];
    return value === undefined ? '' : value;
  }

  function apply(lang) {
    current = SUPPORTED.indexOf(lang) === -1 ? 'ru' : lang;
    var pack = DICT[current] || DICT.ru;

    document.documentElement.lang = current === 'kk' ? 'kk' : 'ru';

    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var value = pack[el.getAttribute('data-i18n')];
      if (value !== undefined) el.textContent = value;
    });

    document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
      var value = pack[el.getAttribute('data-i18n-html')];
      if (value !== undefined) el.innerHTML = value;
    });

    document.querySelectorAll('[data-i18n-aria-label]').forEach(function (el) {
      var value = pack[el.getAttribute('data-i18n-aria-label')];
      if (value !== undefined) el.setAttribute('aria-label', value);
    });

    // Метаданные страницы
    document.title = t('meta.title');
    var desc = document.getElementById('meta-description');
    if (desc) desc.setAttribute('content', t('meta.description'));
    var ogTitle = document.getElementById('og-title');
    if (ogTitle) ogTitle.setAttribute('content', t('meta.ogTitle'));
    var ogDesc = document.getElementById('og-description');
    if (ogDesc) ogDesc.setAttribute('content', t('meta.ogDescription'));

    // Состояние переключателя
    document.querySelectorAll('[data-lang]').forEach(function (btn) {
      var active = btn.getAttribute('data-lang') === current;
      btn.classList.toggle('is-active', active);
      btn.setAttribute('aria-pressed', String(active));
    });

    // У бургера aria-label зависит от состояния меню
    var burger = document.getElementById('burger');
    if (burger) {
      var open = burger.getAttribute('aria-expanded') === 'true';
      burger.setAttribute('aria-label', t(open ? 'a11y.menuClose' : 'a11y.menuOpen'));
    }

    writeStorage(current);

    // Событие для будущих экранов (профиль, канбан)
    document.dispatchEvent(new CustomEvent('pm:lang', { detail: { lang: current } }));
  }

  // Публичный мини-API
  window.PM_t = t;
  window.PM_lang = function () { return current; };
  window.PM_setLang = apply;

  document.addEventListener('click', function (event) {
    var btn = event.target.closest('[data-lang]');
    if (!btn) return;
    var lang = btn.getAttribute('data-lang');
    if (lang && lang !== current) apply(lang);
  });

  apply(detect());
})();
